export function answer(q: string): string {
  const t = q.toLowerCase().replace(/\s+/g, " ");
  let best: QA | null = null;
  let bestScore = 0;
  for (const qa of KB) {
    const score = qa.keys.reduce((s, k) => s + (t.includes(k.toLowerCase()) ? 1 : 0), 0);
    if (score > bestScore) {
      bestScore = score;
      best = qa;
    }
  }
  if (best && bestScore > 0) return best.a;
  return "저는 WattWise에 대해 답해드려요 🙂  ‘전력 거래’, ‘오토인코더’, ‘필요성’, ‘데이터 수집’, ‘실험 결과’ 같은 걸 물어보세요. 아래 추천 질문을 눌러도 돼요!";
}
